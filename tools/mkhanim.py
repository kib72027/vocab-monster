#!/usr/bin/env python3
"""Cut a hero's ChatGPT animation strips into transparent frames and generate src/part_hanim.js.
Input : assets/heroes/<hero>/source/{idle_6f,attack_6f,hit_4f,victory_6f}.jpg   (one horizontal strip per action, green #00FF00 background)
Output: assets/heroes/<hero>/frames/<action>_<n>.png   (transparent, all frames share one canvas size so feet/body stay aligned)
        src/part_hanim.js  (HANIM[hid] = {idle,attack,hit,win} lists of base64 WebP frames; HSPR[hid] = static portrait)
Usage : python3 tools/mkhanim.py h2 h2-mage      (hero id, folder name)   -> then python3 build.py"""
import sys,os,io,base64,json
import numpy as np
from PIL import Image
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CW=360   # common canvas width (frame cell ~170px + room for staff/weapon swing)
ACT=[('idle','idle_6f',6),('attack','attack_6f',6),('hit','hit_4f',4),('win','victory_6f',6)]
def key(im):
    a=np.asarray(im.convert('RGB')).astype(np.float32);r,g,b=a[...,0],a[...,1],a[...,2]
    d=g-np.maximum(r,b);al=np.clip((70-d)/50,0,1)
    g2=np.where(d>0,np.maximum(r,b),g)            # despill green fringe
    out=np.dstack([r,g2,b,al*255]).astype(np.uint8);return Image.fromarray(out,'RGBA')
def split(al,n):
    W=al.shape[1];cnt=(al>0.3).sum(0);cuts=[0]
    for i in range(1,n):
        c=int(i*W/n);lo,hi=max(1,c-28),min(W-1,c+28);cuts.append(lo+int(np.argmin(cnt[lo:hi])))
    cuts.append(W);return cuts
def webp(im,q=88):
    b=io.BytesIO();im.save(b,'WEBP',quality=q,method=6);return 'data:image/webp;base64,'+base64.b64encode(b.getvalue()).decode()
def main(hid,folder):
    base=os.path.join(R,'assets','heroes',folder);os.makedirs(base+'/frames',exist_ok=True)
    H=None;data={};first=None
    for act,fn,n in ACT:
        im=Image.open(f'{base}/source/{fn}.jpg');k=key(im);al=np.asarray(k)[...,3]/255;W,H=k.size;cw=W/n;cuts=split(al,n);fr=[]
        for i in range(n):
            reg=k.crop((cuts[i],0,cuts[i+1],H));cv=Image.new('RGBA',(CW,H),(0,0,0,0))
            ox=int(round(CW/2-(i+.5)*cw+cuts[i]));cv.alpha_composite(reg,(ox,0)) if 0<=ox<=CW-reg.width else cv.paste(reg,(ox,0))
            cv.save(f'{base}/frames/{act}_{i}.png');fr.append({'u':webp(cv),'w':CW,'h':H})
            if first is None and act=='idle'and i==0:first=cv
        data[act]=fr;print(act,n,'cuts',cuts)
    bb=first.getbbox();pt=first.crop((max(0,bb[0]-4),max(0,bb[1]-4),min(CW,bb[2]+4),min(H,bb[3]+4)));pt.save(f'{base}/frames/portrait.png')
    js='/* generated by tools/mkhanim.py -- per-hero animation frames */\nconst HANIM={};\n'
    js+=f'HANIM[{json.dumps(hid)}]=Object.assign({{k:3.4}},{json.dumps(data,separators=(",",":"))});\n'
    js+=f'HSPR[{json.dumps(hid)}]={{u:{json.dumps(webp(pt,90))},w:{pt.width},h:{pt.height}}};\n'
    out=os.path.join(R,'src',f'part_hanim_{hid}.js');open(out,'w',encoding='utf-8').write(js);print('wrote',out,len(js)//1024,'KB')
if __name__=='__main__':main(sys.argv[1],sys.argv[2])
