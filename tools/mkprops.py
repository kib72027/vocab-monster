#!/usr/bin/env python3
"""Props and helpers that replace emoji objects -> src/part_props.js (PROPS = {name: {u, w, h}}).
Input : assets/props/*.jpg made with docs/prop-spritesheet-prompt.md (grid sheets on pure green, nature on magenta).
        Two versions were generated of each; SHEETS says which file, its grid and the name of every cell.
Each cell is cut on the grid (trimmed a little: some sheets draw grid lines), keyed (tools/nmcut2.key), cropped to the
object and scaled down. Pointed things (dagger, spear, rocket) are turned to point straight RIGHT so the engine can aim
them with the flight direction. Helper frames (robot0-3, turret0-3) keep one shared size so they do not jump.
Usage : python3 tools/mkprops.py   (cut-outs also saved to assets/props/cut/ for review)"""
import os,io,sys,json,base64
import numpy as np
from PIL import Image
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from nmcut2 import key,bleed
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D=os.path.join(R,'assets','props')
SHEETS=[('robot.jpg',2,['robot0','robot1','robot2','robot3']),
        ('turret.jpg',2,['turret0','turret1','turret2','turret3']),
        ('weapons-1.jpg',4,['dagger','spear','wrench','bolt','gear','gear2','rocket','bomb','shield','orb','hourglass','heart','feather','paw','crystal','iceshard']),
        ('nature.jpg',2,['leaf','vine','blossom','petal'])]
TURN={'dagger':-45,'spear':-45,'rocket':-40}   # degrees (counter-clockwise) so the point faces right
INSET=.03
INSETS={'robot.jpg':.065}   # this sheet draws thick white lines around and between the cells
def despill(rgba,green):
    """glows were painted over the key colour: take the leaked green (or magenta) back out and thin that haze"""
    a=rgba.astype(np.float32);r,g,b=a[...,0],a[...,1],a[...,2]
    if green:ex=np.clip(g-np.maximum(r,b),0,None);a[...,1]=g-ex
    else:ex=np.clip(np.minimum(r,b)-g,0,None);a[...,0]=r-ex;a[...,2]=b-ex
    a[...,3]=a[...,3]*np.clip(1-ex/110,0,1);return np.clip(a,0,255).astype(np.uint8)
def enc(im):
    b=io.BytesIO();bleed(im).save(b,'WEBP',quality=84,method=4,exact=True);return base64.b64encode(b.getvalue()).decode()
def main():
    out={};os.makedirs(os.path.join(D,'cut'),exist_ok=True)
    for f,n,names in SHEETS:
        a=np.asarray(Image.open(os.path.join(D,f)).convert('RGB'));H,W=a.shape[:2];cw,ch=W/n,H/n;group=[];ins=INSETS.get(f,INSET)
        for i,name in enumerate(names):
            r,c=divmod(i,n);x0,y0,x1,y1=int(c*cw+cw*ins),int(r*ch+ch*ins),int((c+1)*cw-cw*ins),int((r+1)*ch-ch*ins)
            rgba,kind=key(np.ascontiguousarray(a[y0:y1,x0:x1]));im=Image.fromarray(despill(rgba,kind=='green'))
            if name in TURN:im=im.rotate(TURN[name],resample=Image.BICUBIC,expand=True)
            group.append((name,im))
        helper=f.startswith(('robot','turret'))
        if helper:   # one shared crop box for all frames of a helper (no jumping between poses), feet on the bottom
            box=None
            for _,im in group:
                b=im.getbbox();box=b if box is None else (min(box[0],b[0]),min(box[1],b[1]),max(box[2],b[2]),max(box[3],b[3]))
            group=[(nm,im.crop(box)) for nm,im in group]
        for name,im in group:
            if not helper:im=im.crop(im.getbbox())
            mx=360 if helper else 200;s=min(1,mx/max(im.size))
            if s<1:im=im.resize((round(im.width*s),round(im.height*s)),Image.LANCZOS)
            im.save(os.path.join(D,'cut',name+'.png'));out[name]={'u':'data:image/webp;base64,'+enc(im),'w':im.width,'h':im.height}
        print(f' {f}: {", ".join(names)}')
    js='/* generated by tools/mkprops.py from assets/props/ */\nconst PROPS='+json.dumps(out,separators=(',',':'))+';\n'
    open(os.path.join(R,'src','part_props.js'),'w',encoding='utf-8').write(js);print('wrote src/part_props.js',len(js)//1024,'KB')
if __name__=='__main__':main()
