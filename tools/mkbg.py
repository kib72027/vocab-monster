#!/usr/bin/env python3
"""Battle backgrounds -> src/part_bg.js
Input : assets/backgrounds/backgrounds.json  ({key, file, py, types}) + the images it lists (made by an image AI with
        docs/background-prompt.md: wide, empty platform in the lower middle).
Output: src/part_bg.js with BGS = {key:{u,w,h,py,amb}} (amb = ambient animation: clouds, falls, smoke, circle glow, fx) and BGT = {monster type: key} (missing types use 'default').
Usage : python3 tools/mkbg.py"""
import os,io,json,base64
from PIL import Image
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D=os.path.join(R,'assets','backgrounds')
MAXW=1920
def main():
    cfg=json.load(open(os.path.join(D,'backgrounds.json'),encoding='utf-8'))['backgrounds']
    bgs={};bgt={}
    for b in cfg:
        im=Image.open(os.path.join(D,b['file'])).convert('RGB')
        if im.width>MAXW:im=im.resize((MAXW,round(im.height*MAXW/im.width)),Image.LANCZOS)
        buf=io.BytesIO();im.save(buf,'WEBP',quality=80,method=4)
        bgs[b['key']]={'u':'data:image/webp;base64,'+base64.b64encode(buf.getvalue()).decode(),'w':im.width,'h':im.height,'py':b['py'],'amb':b.get('amb')}
        for t in b['types']:bgt[t]=b['key']
        print(f" {b['key']}: {im.width}x{im.height}, {len(buf.getvalue())//1024} KB, types {b['types']}")
    js='/* generated by tools/mkbg.py from assets/backgrounds/ */\nconst BGS='+json.dumps(bgs,separators=(',',':'))+';\nconst BGT='+json.dumps(bgt)+';\n'
    open(os.path.join(R,'src','part_bg.js'),'w',encoding='utf-8').write(js);print('wrote src/part_bg.js',len(js)//1024,'KB')
if __name__=='__main__':main()
