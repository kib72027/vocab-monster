#!/usr/bin/env python3
"""Effect animations -> src/part_vfx.js (VFX = {name: {u: [16 frame data URIs]}}).
Input : assets/vfx/*.jpg, image-AI sprite sheets made with docs/vfx-spritesheet-prompt.md: 4x4 grid = 16 frames of one
        animation (left->right, top->bottom) on pure black. Two versions were generated of each; PICK says which one is used.
The black background becomes transparent by brightness (glow art: alpha = brightness, colour un-mixed from black), each
cell is trimmed a little on every side (some sheets draw thin grid lines between the cells), frames keep the cell's
framing so the animation does not jump. Frames are saved to assets/vfx/cut/<name>.png (one strip) for review.
Usage : python3 tools/mkvfx.py"""
import os,io,json,base64
import numpy as np
from PIL import Image
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D=os.path.join(R,'assets','vfx')
PICK={'fire_burst':'fire_burst.jpg','flame_loop':'flame_loop-1.jpg','ice_burst':'ice_burst.jpg','lightning':'lightning-1.jpg',
      'leaf_swirl':'leaf_swirl-1.jpg','holy_burst':'holy_burst-1.jpg','dark_burst':'dark_burst.jpg','hit_spark':'hit_spark-1.jpg',
      'slash_arc':'slash_arc-1.jpg','water_splash':'water_splash.jpg','smoke_puff':'smoke_puff-1.jpg'}
SIZE=224        # frame size in pixels (square)
INSET=.025      # trim 2.5% of the cell on each side: removes grid lines
def glow(a):
    a=a.astype(np.float32);m=a.max(-1);A=np.clip((m-16)/170,0,1)
    rgb=np.where(A[...,None]>.02,a/np.maximum(A[...,None],.02),0)
    return np.dstack([np.clip(rgb,0,255),A*255]).astype(np.uint8)
_e=np.minimum(np.arange(SIZE),np.arange(SIZE)[::-1])/(SIZE*.07);_e=np.clip(_e,0,1)
EDGE=np.minimum(_e[:,None],_e[None,:])   # fade the last 7% at each edge: no hard square edge when a glow reaches the cell border
def main():
    out={};os.makedirs(os.path.join(D,'cut'),exist_ok=True);total=0
    for name,f in PICK.items():
        g=glow(np.asarray(Image.open(os.path.join(D,f)).convert('RGB')));H,W=g.shape[:2];cw,ch=W/4,H/4;frames=[];strip=Image.new('RGBA',(SIZE*16,SIZE))
        for i in range(16):
            r,c=divmod(i,4);x0,y0=int(c*cw+cw*INSET),int(r*ch+ch*INSET);x1,y1=int((c+1)*cw-cw*INSET),int((r+1)*ch-ch*INSET)
            im=Image.fromarray(g[y0:y1,x0:x1]).resize((SIZE,SIZE),Image.LANCZOS);a=np.asarray(im).copy();a[...,3]=(a[...,3]*EDGE).astype(np.uint8);im=Image.fromarray(a);strip.paste(im,(i*SIZE,0))
            b=io.BytesIO();im.save(b,'WEBP',quality=78,method=4);total+=len(b.getvalue());frames.append('data:image/webp;base64,'+base64.b64encode(b.getvalue()).decode())
        strip.save(os.path.join(D,'cut',name+'.png'));out[name]={'u':frames};print(f' {name}: 16 frames from {f}')
    js='/* generated by tools/mkvfx.py from assets/vfx/ */\nconst VFX='+json.dumps(out,separators=(',',':'))+';\n'
    open(os.path.join(R,'src','part_vfx.js'),'w',encoding='utf-8').write(js);print('wrote src/part_vfx.js',len(js)//1024,'KB (images',total//1024,'KB)')
if __name__=='__main__':main()
