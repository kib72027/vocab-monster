#!/usr/bin/env python3
"""Effect art for ultimates -> src/part_fx.js (FXSPR = {key: {u, w, h}}).
Input (assets/heroes/h8/finisher/):
  beasts.jpg  2x2 grid on magenta: fire cat, ice fox, thunder rabbit, forest panda (all facing right)
  lion.jpg    glowing lion leaping + golden summoning circle on black (glow art: alpha comes from brightness)
Usage: python3 tools/mkfx.py   (cut-outs also saved to assets/heroes/h8/finisher/cut/ for review)"""
import os,io,sys,base64,json
import numpy as np
from PIL import Image
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from nmcut2 import key,cells,bleed
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D=os.path.join(R,'assets','heroes','h8','finisher')
def crop(im,maxw):
    a=np.asarray(im);ys,xs=np.nonzero(a[...,3]>12)
    im=im.crop((max(0,xs.min()-4),max(0,ys.min()-4),xs.max()+5,ys.max()+5))
    if im.width>maxw:im=im.resize((maxw,round(im.height*maxw/im.width)),Image.LANCZOS)
    return im
def glow(a):
    """black-background glow art -> RGBA: alpha = brightness, colour un-mixed from black (a pixel = A*colour)."""
    a=a.astype(np.float32);m=a.max(-1);A=np.clip((m-14)/170,0,1)
    rgb=np.where(A[...,None]>.02,a/np.maximum(A[...,None],.02),0)
    return np.dstack([np.clip(rgb,0,255),A*255]).astype(np.uint8)
def despill(rgba):
    """the beasts' soft glow was painted over magenta: remove the magenta that leaked into it (and thin that haze out)"""
    a=rgba.astype(np.float32);r,g,b=a[...,0],a[...,1],a[...,2];ex=np.clip(np.minimum(r,b)-g,0,None)
    a[...,0]=r-ex;a[...,2]=b-ex;a[...,3]=a[...,3]*np.clip(1-ex/90,0,1)
    return np.clip(a,0,255).astype(np.uint8)
def enc(im):
    b=io.BytesIO();bleed(im).save(b,'WEBP',quality=84,method=4,exact=True);return base64.b64encode(b.getvalue()).decode()
def main():
    out={};os.makedirs(os.path.join(D,'cut'),exist_ok=True)
    a=np.asarray(Image.open(os.path.join(D,'beasts.jpg')).convert('RGB'));rgba,_=key(a);rgba=despill(rgba)
    for name,mk in zip(['h8_cat','h8_fox','h8_rabbit','h8_panda'],cells(rgba[...,3],2,2)):
        p=rgba.copy();p[...,3]=np.where(mk,p[...,3],0);out[name]=crop(Image.fromarray(p),420)
    g=glow(np.asarray(Image.open(os.path.join(D,'lion.jpg')).convert('RGB')));H,W=g.shape[:2]
    # the circle sits in the lower right; the lion's paws never reach below 0.53 of the height on the right half
    cx0,cy0=int(W*.42),int(H*.545)
    lion=g.copy();lion[cy0:,cx0:,3]=0;lion[int(H*.80):,:,3]=0;lion[:,int(W*.66):,3]=0;lion[int(H*.5):,int(W*.55):,3]=0   # drop the circle and its light pillars
    top=int(H*.36);circ=np.zeros_like(g);circ[top:int(H*.86),int(W*.4):int(W*.96)]=g[top:int(H*.86),int(W*.4):int(W*.96)]
    circ[:,:int(W*.66),3][:cy0]=0   # keep the pillars over the circle, not the lion's paw
    fade=np.clip((np.arange(H)-top)/(H*.12),0,1)[:,None];circ[...,3]=(circ[...,3]*fade).astype(np.uint8)   # pillars fade out at the top
    out['h8_lion']=crop(Image.fromarray(lion),640);out['h8_circle']=crop(Image.fromarray(circ),560)
    js={}
    for k,im in out.items():
        im.save(os.path.join(D,'cut',k+'.png'));js[k]={'u':'data:image/webp;base64,'+enc(im),'w':im.width,'h':im.height};print(f' {k}: {im.width}x{im.height}')
    s='/* generated by tools/mkfx.py from assets/heroes/h8/finisher/ */\nconst FXSPR='+json.dumps(js,separators=(',',':'))+';\n'
    open(os.path.join(R,'src','part_fx.js'),'w',encoding='utf-8').write(s);print('wrote src/part_fx.js',len(s)//1024,'KB')
if __name__=='__main__':main()
